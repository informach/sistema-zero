const { chromium, expect } = require('../../packages/molda/node_modules/@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const out = path.join(__dirname, 'implementation');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  async function shot(name) { await page.screenshot({ path: path.join(out, name + '.png'), animations: 'disabled' }); }
  async function snapshot() {
    const menu = page.locator('summary').filter({ hasText: 'Salvar e exportar' });
    if (!await menu.evaluate(el => el.parentElement.open)) await menu.click();
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Baixar projeto', exact: true }).click();
    const download = await pending;
    const data = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    if (await menu.evaluate(el => el.parentElement.open)) await menu.click();
    delete data.thumb; delete data.updatedAt;
    return data;
  }
  try {
    await page.goto('http://127.0.0.1:5216/?oficina=app&nivel=god');
    await page.getByRole('button', { name: 'Criar novo', exact: true }).click();
    await page.getByRole('button', { name: 'Criar modelo', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Aproximar', exact: true })).toBeEnabled();
    const initial = await snapshot();
    await page.getByRole('button', { name: 'Olhar', exact: true }).click();
    const lookCanvas = await page.locator('canvas').first().boundingBox();
    await page.mouse.move(lookCanvas.x + lookCanvas.width / 2, lookCanvas.y + lookCanvas.height / 2);
    await page.mouse.down();
    await page.mouse.move(lookCanvas.x + lookCanvas.width / 2 + 80, lookCanvas.y + lookCanvas.height / 2 + 25, { steps: 8 });
    await page.mouse.up();
    await page.mouse.wheel(0, 90);
    await page.getByRole('button', { name: 'Mover', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Mover', exact: true })).toHaveAttribute('aria-pressed', 'true');
    expect(await snapshot()).toEqual(initial);
    checks.push('visible camera drag and wheel navigation preserve authoring and return to the selected tool');
    await page.getByRole('button', { name: 'Pivô', exact: true }).click();
    await page.getByRole('button', { name: 'Embaixo', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Aplicar', exact: true })).toBeEnabled();
    await shot('pivo-previa');
    await page.getByRole('button', { name: 'Pintar', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'O pivô ainda está em prévia' })).toBeVisible();
    await page.getByRole('button', { name: 'Continuar ajustando', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Aplicar', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    expect(await snapshot()).toEqual(initial);
    await page.getByRole('button', { name: 'Embaixo', exact: true }).click();
    await page.getByRole('button', { name: 'Pintar', exact: true }).click();
    await page.getByRole('button', { name: 'Aplicar pivô', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Pintar', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.getByRole('button', { name: 'Modelar', exact: true }).click();
    const pivoted = await snapshot();
    expect(pivoted.nodes[0].transform).not.toEqual(initial.nodes[0].transform);
    await page.getByRole('button', { name: 'Desfazer', exact: true }).click();
    expect(await snapshot()).toEqual(initial);
    checks.push('pivot preview and cancel preserve source; apply and undo are atomic');
    await page.locator('summary').filter({ hasText: 'Mais ferramentas' }).click();
    await page.getByRole('button', { name: 'Transformar em malha', exact: true }).click();
    await page.getByRole('button', { name: 'Editar malha', exact: true }).click();
    const mesh = await snapshot();
    await page.getByRole('button', { name: 'Dividir pela vista frontal', exact: true }).click();
    const cutCanvas = await page.locator('canvas').first().boundingBox();
    await page.mouse.click(cutCanvas.x + cutCanvas.width / 2, cutCanvas.y + cutCanvas.height / 2 - 65);
    await page.mouse.click(cutCanvas.x + cutCanvas.width / 2, cutCanvas.y + cutCanvas.height / 2 + 65);
    await expect(page.getByRole('button', { name: 'Aplicar', exact: true })).toBeEnabled();
    await shot('divisao-previa');
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    expect(await snapshot()).toEqual(mesh);
    await page.getByRole('button', { name: 'Dividir pela vista frontal', exact: true }).click();
    await page.getByRole('button', { name: 'Dividir no meio', exact: true }).click();
    await page.getByRole('button', { name: 'Aplicar', exact: true }).click();
    const divided = await snapshot();
    expect(Object.keys(divided.geometries[0].faces).length).toBeGreaterThan(Object.keys(mesh.geometries[0].faces).length);
    await page.getByRole('button', { name: 'Desfazer', exact: true }).click();
    expect(await snapshot()).toEqual(mesh);
    checks.push('division preview, cancellation and undo preserve source and keep both sides');
    await page.getByRole('button', { name: 'Voltar às peças', exact: true }).click();
    await page.getByRole('button', { name: 'Animar', exact: true }).click();
    await page.getByRole('button', { name: 'Modelo inteiro', exact: true }).click();
    await page.locator('summary').filter({ hasText: 'Experimentar um movimento pronto' }).click();
    await page.getByRole('button', { name: 'Pular', exact: true }).click();
    await page.getByRole('button', { name: 'Mais devagar', exact: true }).click();
    await page.getByRole('button', { name: 'Mais intenso', exact: true }).click();
    await page.getByRole('button', { name: 'Modelar', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Este movimento ainda está em prévia' })).toBeVisible();
    await page.getByRole('button', { name: 'Continuar ajustando', exact: true }).click();
    await page.getByRole('button', { name: 'Cancelar prévia', exact: true }).click();
    expect(await snapshot()).toEqual(mesh);
    checks.push('preset speed and intensity preview cancel without adding a group or animation');
    await page.getByRole('button', { name: 'Pular', exact: true }).click();
    await page.getByRole('button', { name: 'Modelar', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Guardar este movimento', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Modelar', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.getByRole('button', { name: 'Animar', exact: true }).click();
    checks.push('leaving pivot and preset previews asks once, preserves Continue and resumes the requested activity after Apply');
    const animated = await snapshot();
    const animationTools = page.locator('summary').filter({ hasText: 'Mais ferramentas' });
    if (!await animationTools.evaluate(el => el.parentElement.open)) await animationTools.click();
    await page.getByRole('button', { name: 'Pivô', exact: true }).click();
    await page.getByRole('button', { name: 'Embaixo', exact: true }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Essa peça já tem movimentos' })).toBeVisible();
    expect(await snapshot()).toEqual(animated);
    await page.getByRole('button', { name: 'Mover', exact: true }).click();
    checks.push('pivot in animation blocks an unsupported animated target with explanation and preserves the clip');
    await page.setViewportSize({ width: 1024, height: 600 });
    await expect(page.getByRole('tab', { name: 'Movimentos', exact: true })).toBeVisible();
    await page.getByRole('tab', { name: 'Movimentos', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: 'Peças', exact: true })).toHaveAttribute('aria-selected', 'true');
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: 'Pose', exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(page.getByRole('button', { name: 'Mais tempo · +2 s', exact: true })).toBeVisible();
    await shot('animar-compacto-pose');
    checks.push('compact animation keeps movements, pieces and pose separately reachable');
    for (const [width, height] of [[683, 384], [512, 300]]) {
      await page.setViewportSize({ width, height });
      await page.getByRole('tab', { name: 'Pose', exact: true }).click();
      await expect(page.getByRole('button', { name: 'Mais tempo · +2 s', exact: true })).toBeVisible();
      const canvas = await page.locator('canvas').first().boundingBox();
      expect(canvas.width).toBeGreaterThan(300);
      expect(canvas.height).toBeGreaterThan(200);
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await shot(`zoom-equivalente-${width}`);
    }
    checks.push('reflow at 683x384 and 512x300 keeps stage and inspector reachable without page overflow');
    expect(errors).toEqual([]);
    fs.writeFileSync(path.join(out, 'advanced.json'), JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ checks, errors }));
  } catch (error) { await shot('advanced-failure'); fs.writeFileSync(path.join(out, 'advanced-failure.json'), JSON.stringify({ checks, errors, error: String(error) }, null, 2)); throw error; }
  finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
