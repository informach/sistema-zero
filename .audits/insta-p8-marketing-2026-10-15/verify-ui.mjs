import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { writeFile } from 'node:fs/promises'
const desktop = createRequire(new URL('../../packages/marketing-desktop/package.json', import.meta.url))
const funnel = createRequire(new URL('../../packages/funnel/package.json', import.meta.url))
const { createServer } = await import(pathToFileURL(desktop.resolve('vite')).href)
const { default: tailwindcss } = await import(pathToFileURL(desktop.resolve('@tailwindcss/vite')).href)
const { chromium } = funnel('playwright')
const server = await createServer({ configFile: false, root: fileURLToPath(new URL('./ui-proof', import.meta.url)), plugins: [tailwindcss()], resolve: { alias: { react: fileURLToPath(new URL('../../packages/marketing-workbench/node_modules/react', import.meta.url)), 'react-dom': fileURLToPath(new URL('../../packages/marketing-workbench/node_modules/react-dom', import.meta.url)) }, dedupe: ['react', 'react-dom'] }, server: { host: '127.0.0.1', port: 15467, strictPort: true, fs: { allow: [fileURLToPath(new URL('../..', import.meta.url))] } } })
await server.listen()
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
const page = await context.newPage(), errors = []
page.setDefaultTimeout(15000)
page.on('pageerror', (error) => errors.push(error.message))
try {
  await page.goto('http://127.0.0.1:15467')
  await page.getByRole('button', { name: 'Revisar conversa', exact: true }).click()
  await page.getByLabel('Palavra da peça', { exact: true }).fill('PRIMEIRO')
  await page.getByText('PRIMEIRO pode ocorrer em comentários incidentais.', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Salvar revisão', exact: true }).click()
  await page.waitForFunction(() => window.proof.drafts.length === 1)
  assert.equal(await page.evaluate(() => window.proof.commands.length), 0)
  await page.getByLabel('Conferi a oferta publicada', { exact: false }).check()
  await page.getByRole('button', { name: 'Aprovar texto desta revisão' }).click()
  await page.getByText('Texto desta revisão aprovado.', { exact: false }).waitFor()
  await page.getByLabel('Publicação do formato selecionado').selectOption(await page.evaluate(() => window.proof.publicationId))
  assert.equal(await page.getByRole('button', { name: 'Solicitar ativação desta revisão' }).isDisabled(), true)
  await page.getByLabel('Conferi que a palavra', { exact: false }).check()
  assert.equal(await page.getByRole('button', { name: 'Solicitar ativação desta revisão' }).isEnabled(), true)
  await page.getByRole('combobox', { name: /^Conta/ }).selectOption(await page.evaluate(() => window.proof.accountId))
  await page.getByRole('button', { name: /Contato de revisão/ }).click()
  await page.getByRole('button', { name: 'Assumir e pausar automação' }).click()
  await page.getByRole('heading', { name: /Contato de revisão · Assumida/ }).waitFor()
  await page.getByLabel('Resposta da equipe', { exact: true }).fill('Resposta privada de teste')
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Enviar resposta', exact: true }).click()
  assert.equal(await page.evaluate(() => window.proof.replies.size), 0)
  await context.setOffline(false)
  await page.getByRole('button', { name: 'Enviar resposta', exact: true }).click()
  await page.getByRole('button', { name: 'Consultar a mesma tentativa' }).waitFor()
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Consultar a mesma tentativa' }).click()
  assert.equal(await page.evaluate(() => window.proof.commands.filter((c) => c.body.action === 'reply').length), 1)
  await context.setOffline(false)
  await page.getByRole('button', { name: 'Consultar a mesma tentativa' }).click()
  await page.waitForFunction(() => window.proof.commands.filter((c) => c.body.action === 'reply').length === 2)
  assert.equal(await page.evaluate(() => window.proof.replies.size), 1)
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: fileURLToPath(new URL('./ui-desktop.png', import.meta.url)), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('details').evaluateAll((details) => { for (const detail of details) detail.open = true })
  await page.getByRole('combobox', { name: /^Resposta aprovada/ }).selectOption('community')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: fileURLToPath(new URL('./ui-mobile.png', import.meta.url)), fullPage: true })
  assert.deepEqual(errors, [])
  const result = { passed: true, checks: ['salvar cria somente revisão', 'aviso MC08', 'aprovação separada', 'compatibilidade da publicação obrigatória', 'tomada humana', 'offline não enfileira', 'retry após offline conserva operationId', 'nenhuma DM em storage', 'sem overflow desktop/mobile com painéis abertos e D02', 'sem erro de runtime'], browser: await browser.version(), at: new Date().toISOString() }
  await writeFile(new URL('./ui-validation.json', import.meta.url), `${JSON.stringify(result, null, 2)}\n`)
  console.log(JSON.stringify(result))
} catch (error) {
  console.error(await page.locator('body *').evaluateAll((nodes) => nodes.filter((node) => node.getBoundingClientRect().right > innerWidth).slice(0, 20).map((node) => ({ tag: node.tagName, class: node.className, right: node.getBoundingClientRect().right, text: node.textContent?.slice(0, 100) }))))
  await page.screenshot({ path: fileURLToPath(new URL('./ui-failure.png', import.meta.url)), fullPage: true })
  throw error
} finally { await browser.close(); await server.close() }
