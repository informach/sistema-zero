import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, resolve } from 'node:path'
import sharp from 'sharp'
import { prepareWebArtwork } from '../../packages/edisvg/src/data'

const archive = resolve(import.meta.dir, '../../art/edisvg/exports')
const target = resolve(import.meta.dir, '../../packages/edisvg/assets')
const source = JSON.parse(await readFile(resolve(archive, 'manifest.json'), 'utf8'))
const hash = (value: string | Uint8Array) => createHash('sha256').update(value).digest('hex')
const choices = {
  happy: 'saudacao-b1-a1',
  celebrating: 'celebrando-b1-a1',
  thinking: 'pensando-b1-a1',
  sleeping: 'dormindo-b1-a2',
  speaking: 'zappy-falando-b1-a1',
  chest: 'bau-b1-a1',
  chestOpen: 'bau-aberto-b1-a1',
} as const
const files: Record<string, { sha256: string; bytes: number }> = {}
const refs: Record<string, unknown> = {}
const measurements: Record<string, { original: number; runtime: number; poster: number }> = {}
await mkdir(target, { recursive: true })
for (const [role, key] of Object.entries(choices)) {
  const entry = source.artifacts.find((value: { key: string }) => value.key === key)
  if (!entry || typeof entry.file !== 'string' || basename(entry.file) !== entry.file)
    throw new Error(`Arte ausente: ${role}`)
  const original = await readFile(resolve(archive, entry.file), 'utf8')
  if (hash(original) !== entry.sha256) throw new Error(`Arte alterada: ${role}`)
  const prepared = prepareWebArtwork(original)
  assert.deepEqual(JSON.parse(prepared.content).document, JSON.parse(original).document)
  if (role === 'speaking')
    assert.ok(
      prepared.info.inputs.some((input) => input.name === 'falando' && input.kind === 'boolean'),
    )
  if (role === 'chest')
    assert.ok(
      prepared.info.inputs.some((input) => input.name === 'aberto' && input.kind === 'boolean'),
    )
  const encodedPoster = await sharp(prepared.poster.bytes)
    .webp({ lossless: true, exact: true, effort: 5 })
    .toBuffer()
  const originalPixels = await sharp(prepared.poster.bytes).ensureAlpha().raw().toBuffer()
  const encodedPixels = await sharp(encodedPoster).ensureAlpha().raw().toBuffer()
  assert.deepEqual(encodedPixels, originalPixels, `A reserva ${role} deve preservar cada pixel.`)
  const sha256 = hash(prepared.content),
    posterSha = hash(encodedPoster)
  const artFile = `${role}.${sha256.slice(0, 12)}.edi-animation.json`
  const posterFile = `${role}.${posterSha.slice(0, 12)}.webp`
  await writeFile(resolve(target, artFile), prepared.content)
  await writeFile(resolve(target, posterFile), encodedPoster)
  files[artFile] = { sha256, bytes: Buffer.byteLength(prepared.content) }
  files[posterFile] = { sha256: posterSha, bytes: encodedPoster.byteLength }
  refs[role] = {
    format: 'edi-animation',
    version: 1,
    title: prepared.info.title,
    url: `/edisvg/${artFile}`,
    sha256,
    bytes: files[artFile].bytes,
    poster: {
      url: `/edisvg/${posterFile}`,
      width: prepared.poster.width,
      height: prepared.poster.height,
      sha256: posterSha,
    },
  }
  measurements[role] = {
    original: Buffer.byteLength(original),
    runtime: files[artFile].bytes,
    poster: encodedPoster.byteLength,
  }
}
await writeFile(
  resolve(target, 'manifest.json'),
  `${JSON.stringify({ version: 1, files, measurements }, null, 2)}\n`,
)
await writeFile(
  resolve(import.meta.dir, '../../packages/edisvg/src/builtins.generated.ts'),
  `// Generated by scripts/edisvg/prepare-builtins.ts from qualified editable projects.\nexport const BUILTIN_ART = ${JSON.stringify(refs, null, 2)} as const\n\nexport type ZappyExpression = 'happy' | 'celebrating' | 'thinking' | 'sleeping' | 'speaking'\n`,
)
console.log(
  JSON.stringify({ roles: Object.keys(refs), files: Object.keys(files).length, measurements }),
)
