function sections(...names: readonly string[]): PaletteSection[] {
  return names.map((name) => {
    const section = SECTIONS.find((entry) => entry.name === name)
    if (!section) throw new Error(`Seção desconhecida do Jogo 2D Avançado: ${name}`)
    return section
  })
}

function kit(name: string, ...names: readonly string[]): PaletteSection {
  return { name, types: sections(...names).flatMap((section) => [...section.types]) }
}

