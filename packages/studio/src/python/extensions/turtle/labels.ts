/** Turtle palette categories, in teaching order. */
export const TURTLE_CATEGORIES = [
  'Movimento',
  'Caneta e cores',
  'Aparência',
  'Tartarugas',
  'Tela',
  'Eventos',
  'Animação e tempo',
] as const
type TurtleCategory = (typeof TURTLE_CATEGORIES)[number]

/** One teaching concept: a Turtle/Screen/Shape method and its procedural turtle.* twin. */
export interface TurtleConcept {
  /** Class that owns the concept; 'turtle' means a module-only function (Turtle(), done()). */
  owner: 'Turtle' | 'Screen' | 'Shape' | 'turtle'
  canonical: string
  title: string
  category: TurtleCategory
  level: 1 | 2 | 3
  help: string
  role: 'statement' | 'value'
  params?: readonly PythonApiParam[]
  variadic?: { label: string; minimum?: number; defaults?(): PythonNode[] }
  starter?: boolean
  /** A setter also used as a getter (pencolor()): adds a hidden value block for the getter. */
  getter?: boolean
  /** The getter's name when "<title> atual" would say something else (stamp gives a number). */
  getterTitle?: string
}

const n = (value: number) => () => integer(String(value))
const t = (value: string) => () => text(value)
const fn = (value: string) => () => name(value)
const signed = (value: number) =>
  value < 0
    ? node('UnaryOp', { op: node('USub'), operand: integer(String(-value)) })
    : integer(String(value))
const pair = (x: number, y: number) =>
  node('Tuple', { elts: [signed(x), signed(y)], ctx: node('Load') })
export const TURTLE_POLYGON_EXAMPLE = node('Tuple', {
  elts: [pair(0, 10), pair(10, 0), pair(0, -10)],
  ctx: node('Load'),
})
const button = optional('btn', 'botão', n(1))
const add = optional('add', 'somar ao anterior', () => boolean(true))

