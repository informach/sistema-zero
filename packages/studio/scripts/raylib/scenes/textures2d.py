# Cena-gabarito 2D: texturas, operações de imagem, blend, recorte e câmera girada.
from pyray import *

init_window(400, 300, 'gabarito')
xadrez = load_texture_from_image(gen_image_checked(32, 32, 8, 8, RED, WHITE))
degrade = gen_image_gradient_linear(48, 24, 90, BLUE, YELLOW)
grad = load_texture_from_image(degrade)
liso = load_texture_from_image(degrade)
set_texture_filter(liso, TEXTURE_FILTER_BILINEAR)

seta = gen_image_color(24, 16, BLANK)
image_draw_rectangle(seta, 0, 6, 16, 4, DARKGREEN)
image_draw_rectangle(seta, 16, 2, 8, 12, DARKGREEN)
image_draw_pixel(seta, 0, 0, RED)
seta_tex = load_texture_from_image(seta)

cinza = image_copy(degrade)
image_color_grayscale(cinza)
cinza_tex = load_texture_from_image(cinza)
avesso = image_copy(degrade)
image_color_invert(avesso)
image_flip_horizontal(avesso)
avesso_tex = load_texture_from_image(avesso)
deitada = image_copy(seta)
image_rotate_cw(deitada)
deitada_tex = load_texture_from_image(deitada)
grande = image_copy(seta)
image_resize_nn(grande, 48, 32)
image_crop(grande, Rectangle(8, 0, 40, 32))
image_color_tint(grande, ORANGE)
grande_tex = load_texture_from_image(grande)

camera = Camera2D(Vector2(320, 240), Vector2(0, 0), 30, 2)
quadros = 0
while not window_should_close():
    quadros += 1
    begin_drawing()
    clear_background(RAYWHITE)
    draw_texture(xadrez, 10, 10, WHITE)
    draw_texture_ex(xadrez, Vector2(60, 10), 15, 1.5, WHITE)
    draw_texture_v(grad, Vector2(120, 10), WHITE)
    draw_texture_rec(xadrez, Rectangle(0, 0, -16, 16), Vector2(180, 10), WHITE)
    draw_texture_rec(xadrez, Rectangle(4, 4, 16, -16), Vector2(200, 10), WHITE)
    draw_texture_pro(seta_tex, Rectangle(0, 0, 24, 16), Rectangle(250, 40, 48, 32), Vector2(24, 16), 45, WHITE)
    draw_texture_pro(seta_tex, Rectangle(0, 0, -24, 16), Rectangle(310, 20, 48, 32), Vector2(0, 0), 0, SKYBLUE)
    draw_texture_pro(seta_tex, Rectangle(0, 0, 24, -16), Rectangle(310, 60, 24, 16), Vector2(0, 0), 0, WHITE)
    draw_texture_pro(liso, Rectangle(0, 0, 48, 24), Rectangle(10, 60, 96, 48), Vector2(0, 0), 0, WHITE)
    draw_texture(cinza_tex, 120, 60, WHITE)
    draw_texture(avesso_tex, 120, 90, WHITE)
    draw_texture(deitada_tex, 180, 60, WHITE)
    draw_texture(grande_tex, 210, 90, WHITE)
    draw_texture(xadrez, 360, 100, fade(WHITE, 0.4))

    draw_rectangle(10, 130, 120, 50, DARKGRAY)
    begin_blend_mode(BLEND_ADDITIVE)
    draw_circle(45, 155, 22, RED)
    draw_circle(70, 155, 22, GREEN)
    end_blend_mode()
    begin_blend_mode(BLEND_MULTIPLIED)
    draw_circle(105, 155, 22, SKYBLUE)
    end_blend_mode()
    draw_rectangle(140, 130, 120, 50, GRAY)
    begin_blend_mode(BLEND_ADD_COLORS)
    draw_circle(170, 155, 22, (120, 40, 40, 255))
    end_blend_mode()
    begin_blend_mode(BLEND_SUBTRACT_COLORS)
    draw_circle(225, 155, 22, (60, 60, 120, 255))
    end_blend_mode()

    begin_scissor_mode(20, 200, 60, 40)
    draw_circle(50, 220, 40, PURPLE)
    draw_text('recorte', 22, 230, 20, YELLOW)
    end_scissor_mode()

    begin_mode_2d(camera)
    draw_texture(xadrez, -16, -16, WHITE)
    draw_rectangle_lines(-20, -20, 40, 40, BLACK)
    draw_line(0, 0, 30, 0, BLUE)
    end_mode_2d()
    end_drawing()
    if quadros == 3:
        take_screenshot('textures2d.png')
        break
close_window()
