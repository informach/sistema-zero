import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { collectBundleLicenses } from '../../../scripts/lib/bundle-licenses'
import { THREE_VERSION } from '../src/three/threeRuntimeContract'

const raiz = resolve(import.meta.dirname, '../../..'),
  permitidos = new Set([
    'three',
    'three/addons/loaders/GLTFLoader.js',
    'three/addons/utils/SkeletonUtils.js',
  ])
if (Bun.version !== '1.3.11') throw Error('Gere o runtime com Bun 1.3.11, como no CI.')
if (
  JSON.parse(readFileSync(resolve(raiz, 'packages/studio/package.json'), 'utf8')).dependencies
    .three !== THREE_VERSION
)
  throw Error('O contrato Three do iframe precisa acompanhar a versão instalada no Estúdio.')
process.chdir(raiz)
async function gerar(entrada: string, destino: string, nome: string) {
  const resultado = await Bun.build({
    entrypoints: [entrada],
    root: raiz,
    target: 'browser',
    format: 'esm',
    splitting: false,
    minify: true,
    sourcemap: 'none',
    packages: 'bundle',
    env: 'disable',
    external: ['three', 'three/*'],
    define: { 'process.env.NODE_ENV': '"production"' },
    metafile: true,
  })
  if (!resultado.success)
    throw new AggregateError(resultado.logs, 'Falha ao empacotar o carregador de cenários.')
  if (resultado.outputs.length !== 1 || !resultado.metafile)
    throw Error('O carregador precisa sair em um módulo único e auditável.')
  const meta = (
      typeof resultado.metafile === 'string' ? JSON.parse(resultado.metafile) : resultado.metafile
    ) as { inputs: Record<string, unknown> },
    arquivos = Object.keys(meta.inputs),
    licencas = collectBundleLicenses(raiz, arquivos),
    avisos = licencas
      .map((l) => `/*! ${l.nome}@${l.versao}\n${l.texto.replaceAll('*/', '* /')}\n*/`)
      .join('\n'),
    fonte = `${avisos}\n${await resultado.outputs[0]!.text()}`,
    scan = new Bun.Transpiler({ loader: 'js' }).scan(fonte),
    imports = [...new Set(scan.imports.map((i) => i.path))].sort(),
    proibido = arquivos.find((p) =>
      /(?:[/\\]src[/\\](?:Palco\.ts|components[/\\]|state[/\\])|GLTFExporter|FBXLoader|[/\\]react[/\\])/.test(
        p,
      ),
    )
  if (proibido) throw Error(`O runtime depende de editor/autoria: ${proibido}`)
  if (
    imports.some((i) => !permitidos.has(i)) ||
    !imports.includes('three') ||
    fonte.length > 1_000_000 ||
    fonte.includes(raiz) ||
    fonte.includes('/@fs/')
  )
    throw Error('O carregador tem imports inesperados, caminhos locais ou excede seu orçamento.')
  const medidas = {
      caracteres: fonte.length,
      sha256: createHash('sha256').update(fonte).digest('hex'),
      imports,
    },
    versoes = licencas.map(({ nome, versao, licenca }) => ({ nome, versao, licenca })),
    texto = `/** Generated by scripts/generate-scene3d-runtime.ts. Do not edit. */\nexport const ${nome}_META = ${JSON.stringify({ ...medidas, threeVersion: THREE_VERSION, dependencias: versoes })} as const\nexport const ${nome} = ${JSON.stringify(fonte)}\n`
  if (process.argv.includes('--check')) {
    if (readFileSync(destino, 'utf8') !== texto)
      throw Error('O carregador gerado está desatualizado. Regenere com Bun 1.3.11.')
  } else writeFileSync(destino, texto)
  console.log(
    `${nome}: ${medidas.caracteres} caracteres, ${imports.length} imports Three compartilhados, SHA-256 ${medidas.sha256}.`,
  )
}
await gerar(
  resolve(raiz, 'packages/studio/src/three/scene3dBootstrap.ts'),
  resolve(raiz, 'packages/studio/src/three/scene3dRuntime.generated.ts'),
  'SCENE3D_RUNTIME',
)
await gerar(
  resolve(raiz, 'packages/studio/src/three/scene3dProBootstrap.ts'),
  resolve(raiz, 'packages/studio/src/three/scene3dProRuntime.generated.ts'),
  'SCENE3D_PRO_RUNTIME',
)
