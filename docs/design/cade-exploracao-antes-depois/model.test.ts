import { expect, test } from 'bun:test'
import { start, reduce, historyStep } from './model'
test('reaction can be enabled before any tap; either hiding place can be first', () => {
  let m = start('touch')
  m = reduce('touch', m, { type: 'connect', port: 'touch', enabled: true })
  expect(m.seen).toEqual({})
  m = reduce('touch', m, { type: 'touch-hiding-place', id: 1 })
  expect(m.state.match.gardenFound).toEqual([1])
  expect(m.seen.responds).toBe(true)
  expect(m.seen['target-0']).toBeUndefined()
  m = reduce('touch', m, { type: 'touch-hiding-place', id: 1 })
  expect(m.state.match.gardenFound).toEqual([1])
  m = reduce('touch', m, { type: 'connect', port: 'touch', enabled: false })
  expect(m.state.match.gardenFound).toEqual([1])
  m = reduce('touch', m, { type: 'touch-hiding-place', id: 0 })
  expect(m.seen['no-response']).toBe(true)
  expect(m.state.match.gardenFound).toEqual([1])
  m = reduce('touch', m, { type: 'new-trial' })
  expect(m.state.match.touch).toBe(false)
  expect(m.state.match.gardenFound ?? []).toEqual([])
  expect(m.seen.responds).toBe(true)
  m = reduce('touch', m, { type: 'connect', port: 'touch', enabled: true })
  m = reduce('touch', m, { type: 'touch-hiding-place', id: 0 })
  expect(m.seen['target-0']).toBe(true)
  expect(m.seen['target-1']).toBe(true)
  m = reduce('touch', m, { type: 'reset-all' })
  expect(m.seen).toEqual({})
})
test('empty first, repeat, restart early and alternative targets all count', () => {
  let m = start('count')
  m = reduce('count', m, { type: 'look-around' })
  expect(m.seen['no-find']).toBe(true)
  m = reduce('count', m, { type: 'find-character', id: 2 })
  m = reduce('count', m, { type: 'find-character', id: 2 })
  expect(m.state.match.points).toBe(1)
  expect(m.seen.repeat).toBe(true)
  m = reduce('count', m, { type: 'restart-search' })
  expect(m.seen['back-to-zero']).toBe(true)
  expect(m.state.match.points).toBe(0)
  m = reduce('count', m, { type: 'find-character', id: 1 })
  m = reduce('count', m, { type: 'find-character', id: 0 })
  expect(
    ['no-find', 'first-find', 'second-find', 'repeat', 'back-to-zero'].every((id) => m.seen[id]),
  ).toBe(true)
  m = reduce('count', m, { type: 'restart-search' })
  expect(m.seen['second-find']).toBe(true)
})

test('undo restores the scene, rule and discoveries together; full reset clears history', () => {
  let history = [start('touch')]
  history = historyStep('touch', history, { type: 'connect', port: 'touch', enabled: true })
  history = historyStep('touch', history, { type: 'touch-hiding-place', id: 1 })
  history = historyStep('touch', history, { type: 'undo' })
  expect(history.at(-1)!.state.match.touch).toBe(true)
  expect(history.at(-1)!.seen).toEqual({})
  expect(history.at(-1)!.state.match.gardenFound ?? []).toEqual([])
  history = historyStep('touch', history, { type: 'reset-all' })
  expect(history).toHaveLength(1)
  expect(history.at(-1)!.state.match.touch).toBe(false)
})
