import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Logger, NodeIO } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import { dedup, prune, quantize, weld } from '@gltf-transform/functions'
import { encodeSceneGlb } from '../../../packages/molda/src/export/sceneGlb'
import { readSceneDocument } from '../../../packages/molda/src/scene/readDocument'

const source = resolve(
  import.meta.dirname,
  '../../design/ilha-do-farol-molda/projetos/cena-completa.molda.json',
)
const read = readSceneDocument(JSON.parse(readFileSync(source, 'utf8')))
if (read.status !== 'valid') throw Error('Cena do Molda inválida')
const glb = encodeSceneGlb(read.document, { allowLosses: true })
if (glb.issues.some((i) => i.code !== 'hidden-node')) throw Error('A cena perdeu dados visuais')
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .setLogger(new Logger(Logger.Verbosity.SILENT))
const optimized = await io.readBinary(glb.bytes)
await optimized.transform(
  weld(),
  dedup(),
  quantize({ quantizePosition: 14, quantizeNormal: 10 }),
  prune(),
)
const bytes = await io.writeBinary(optimized)
writeFileSync(
  resolve(import.meta.dirname, '../../../packages/studio/src/arte/ilha-farol-scene.generated.ts'),
  `// Generated by gerar-ilha-artes.ts from the editable Molda scene.\nexport const ILHA_SCENE_GLB = ${JSON.stringify(`data:model/gltf-binary;base64,${Buffer.from(bytes).toString('base64')}`)}\n`,
)
console.log('Cena das experiências:', bytes.length, 'bytes (antes:', glb.bytes.length, ')')
